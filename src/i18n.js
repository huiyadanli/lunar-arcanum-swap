export function detectLang() {
  const l = (navigator.language || 'zh-CN').toLowerCase();
  return l.startsWith('zh') ? 'zh-CN' : 'en';
}

export function translate(lang, key, vars) {
  let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), DICTS[lang] || zh);
  if (v == null) v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), zh);
  if (v == null) return key;
  if (typeof v === 'string' && vars) v = v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  return v;
}
